#!/usr/bin/env bash
# =============================================================================
# lib/generate.sh — writes the system flake into the new user's home folder
# =============================================================================
# Result (inside the new system):
#
#   /home/<user>/<flake folder>/
#       flake.nix                    entry point: pins nixpkgs, defines the host
#       configuration.nix            your settings (boot, user, keyboard, ...)
#       hardware-configuration.nix   detected by nixos-generate-config
#       desktop.nix                  only if you picked GNOME or Plasma
#       README.md                    how to rebuild
#
# About the "here-documents" used below:
#
#     cat > file <<EOF
#     text with $variables
#     EOF
#
# `cat > file` writes to a file; everything between <<EOF and the line that only
# contains EOF is the text. Because EOF is not quoted, bash replaces $variables
# and ${variables} inside the text with their values. The result is a plain
# Nix file with our choices filled in.

# ----------------------------------------------------------------------------
# generate_flake — main entry
# ----------------------------------------------------------------------------
generate_flake() {
  step "Writing the system flake"

  FLAKE_TARGET_DIR="/home/$CFG_USERNAME/$CFG_FLAKE_NAME"
  FLAKE_LIVE_DIR="$TARGET_ROOT$FLAKE_TARGET_DIR"
  mkdir -p "$FLAKE_LIVE_DIR"

  write_flake_nix
  write_configuration_nix
  if [[ $CFG_PROFILE != minimal ]]; then
    write_desktop_nix
  fi
  write_hardware_config
  write_flake_readme
  ok "Flake written to $FLAKE_TARGET_DIR"
}

# ----------------------------------------------------------------------------
# flake.nix
# ----------------------------------------------------------------------------
write_flake_nix() {
  local nixpkgs_branch="nixos-unstable"
  if [[ $CFG_CHANNEL == stable ]]; then
    nixpkgs_branch="nixos-$NIX_RELEASE"
  fi

  cat >"$FLAKE_LIVE_DIR/flake.nix" <<EOF
{
  description = "NixOS configuration for ${CFG_HOSTNAME}";

  inputs = {
    # Which nixpkgs this system follows. Change the branch to switch channel.
    nixpkgs.url = "github:NixOS/nixpkgs/${nixpkgs_branch}";
  };

  outputs = inputs@{ self, nixpkgs, ... }: {
    # "sudo nixos-rebuild switch --flake .#<name>" builds the entry with that name.
    # Without "#<name>" it uses the machine's hostname, which matches this one.
    nixosConfigurations."${CFG_HOSTNAME}" = nixpkgs.lib.nixosSystem {
      # Lets your modules receive "inputs" as an argument (handy when you add
      # more flake inputs later, e.g. home-manager).
      specialArgs = { inherit inputs; };
      modules = [ ./configuration.nix ];
    };
  };
}
EOF
}

# ----------------------------------------------------------------------------
# configuration.nix  (written in pieces, appended with >>)
# ----------------------------------------------------------------------------
write_configuration_nix() {
  local cfg="$FLAKE_LIVE_DIR/configuration.nix"
  local desktop_import=""
  if [[ $CFG_PROFILE != minimal ]]; then
    desktop_import="./desktop.nix"
  fi

  # --- header, imports and Nix settings --------------------------------------
  cat >"$cfg" <<EOF
# System configuration for ${CFG_HOSTNAME}.
# Generated by the installer script; edit it freely.
{ config, lib, pkgs, ... }:

{
  imports = [
    ./hardware-configuration.nix
    ${desktop_import}
  ];

  # Flakes and the new "nix" command stay enabled on the installed system.
  nix.settings.experimental-features = [ "nix-command" "flakes" ];

  # ---- Boot loader ----
EOF

  # --- boot loader depends on the firmware ------------------------------------
  if [[ $BOOT_MODE == uefi ]]; then
    cat >>"$cfg" <<EOF
  boot.loader.systemd-boot.enable = true;
  boot.loader.systemd-boot.configurationLimit = 10;   # keep the last 10 generations
  boot.loader.efi.canTouchEfiVariables = true;
EOF
  else
    cat >>"$cfg" <<EOF
  boot.loader.grub.enable = true;
  boot.loader.grub.device = "${CFG_DISK}";
EOF
  fi

  # --- disk encryption ---------------------------------------------------------
  if [[ $CFG_ENCRYPT == yes ]]; then
    local luks_uuid
    luks_uuid="$(uuid_of "$PART_ROOT")"
    cat >>"$cfg" <<EOF

  # ---- Disk encryption (LUKS2) ----
  # The initrd asks for the passphrase and opens this partition as /dev/mapper/cryptroot.
  # (mkForce: this value wins over the one auto-detected in hardware-configuration.nix.)
  boot.initrd.luks.devices."cryptroot".device = lib.mkForce "/dev/disk/by-uuid/${luks_uuid}";
EOF
  fi

  # --- keyboard, locale, time, network ----------------------------------------
  cat >>"$cfg" <<EOF

  # ---- Keyboard layout ----
  # console.keyMap is the layout of the text console.
  # console.earlySetup loads it already inside the initrd, so the disk
  # passphrase prompt at boot uses this layout too.
  console.keyMap = "${CFG_KEYMAP}";
  console.earlySetup = true;

  # ---- Language and time ----
  i18n.defaultLocale = "${CFG_LOCALE}";
  time.timeZone = "${CFG_TIMEZONE}";

  # ---- Network ----
  networking.hostName = "${CFG_HOSTNAME}";
  networking.networkmanager.enable = true;

  # Compressed swap in RAM (no swap partition needed).
  zramSwap.enable = true;

  # ---- User ----
  # The password was set during installation (with "passwd" you can change it).
  users.users."${CFG_USERNAME}" = {
    isNormalUser = true;
    description = "${CFG_USERNAME}";
    extraGroups = [ "wheel" "networkmanager" ];   # wheel = may use sudo
  };
EOF

  # --- extra packages -----------------------------------------------------------
  if [[ -n $CFG_PACKAGES ]]; then
    local pkgs=() pkg
    read -ra pkgs <<<"$CFG_PACKAGES"
    {
      printf '\n  # ---- Packages installed for every user ----\n'
      printf '  environment.systemPackages = with pkgs; [\n'
      for pkg in "${pkgs[@]}"; do
        printf '    %s\n' "$pkg"
      done
      printf '  ];\n'
    } >>"$cfg"
  fi

  # --- virtual machine helpers (only when we run inside a VM) -----------------
  if [[ $VIRT == kvm || $VIRT == qemu ]]; then
    cat >>"$cfg" <<EOF

  # ---- Virtual machine integration (detected: ${VIRT}) ----
  services.qemuGuest.enable = true;        # lets the host shut down / query the guest
  services.spice-vdagentd.enable = true;   # clipboard sharing and window resizing
EOF
  fi

  # --- end -----------------------------------------------------------------------
  cat >>"$cfg" <<EOF

  # Do NOT change this when you upgrade; it records the release this machine
  # was first installed with (it keeps old data formats working).
  system.stateVersion = "${NIX_RELEASE}";
}
EOF
}

# ----------------------------------------------------------------------------
# desktop.nix  (only for the gnome / plasma profiles)
# ----------------------------------------------------------------------------
write_desktop_nix() {
  local f="$FLAKE_LIVE_DIR/desktop.nix"
  xkb_from_keymap "$CFG_KEYMAP" # sets XKB_LAYOUT and XKB_VARIANT

  cat >"$f" <<EOF
# Desktop environment (${CFG_PROFILE}).
{ ... }:

{
  services.xserver.enable = true;

  # Keyboard layout for the graphical session. This was derived from the
  # console keymap "${CFG_KEYMAP}" and may need a manual fix for unusual layouts
  # (list of XKB layouts: https://search.nixos.org/options?query=xkb.layout).
  services.xserver.xkb = {
    layout = "${XKB_LAYOUT}";
    variant = "${XKB_VARIANT}";
  };
EOF

  case "$CFG_PROFILE" in
  gnome)
    cat >>"$f" <<EOF

  services.displayManager.gdm.enable = true;
  services.desktopManager.gnome.enable = true;
EOF
    ;;
  plasma)
    cat >>"$f" <<EOF

  services.displayManager.sddm.enable = true;
  services.displayManager.sddm.wayland.enable = true;
  services.desktopManager.plasma6.enable = true;
EOF
    ;;
  esac

  printf '}\n' >>"$f"
}

# ----------------------------------------------------------------------------
# hardware-configuration.nix  (detected from the mounted target)
# ----------------------------------------------------------------------------
write_hardware_config() {
  local f="$FLAKE_LIVE_DIR/hardware-configuration.nix"
  if [[ ${DRY_RUN:-0} == 1 ]]; then
    printf '# (dry run) real output of nixos-generate-config would be here\n{ ... }: { }\n' >"$f"
    return 0
  fi
  # --show-hardware-config prints the file to the screen instead of writing
  # /mnt/etc/nixos; `>` redirects that output into our flake folder.
  nixos-generate-config --root "$TARGET_ROOT" --show-hardware-config >"$f"
}

# ----------------------------------------------------------------------------
# README.md for the user's flake folder
# ----------------------------------------------------------------------------
write_flake_readme() {
  cat >"$FLAKE_LIVE_DIR/README.md" <<EOF
# ${CFG_HOSTNAME} - system flake

Apply changes after editing the .nix files:

    sudo nixos-rebuild switch --flake ~/${CFG_FLAKE_NAME}

Update nixpkgs (and then rebuild):

    cd ~/${CFG_FLAKE_NAME} && nix flake update

Note: this folder is a git repository. Flakes only see files that git knows
about, so after creating a NEW file run \`git add <file>\` before rebuilding.
EOF
}
